# 34. MONTE CARLO PREDICTOR UNCERTAINTY
# ============================================================

def monte_carlo_predictor_uncertainty(

    historical_df,
    future_df,
    predictors,
    n_simulations=5000,
    random_seed=42

):

    rng = np.random.default_rng(
        random_seed
    )

    predictor_sd = {}

    for predictor in predictors:

        values = (
            historical_df[
                predictor
            ]
            .dropna()
        )

        if len(values) >= 2:

            predictor_sd[
                predictor
            ] = float(
                values.std()
            )

        else:

            predictor_sd[
                predictor
            ] = 0.0

    simulations = []

    base_X = future_df[
        predictors
    ].copy()

    for _ in range(
        n_simulations
    ):

        simulated_X = base_X.copy()

        for predictor in predictors:

            sd = predictor_sd[
                predictor
            ]

            if sd > 0:

                noise = rng.normal(

                    0,

                    sd * 0.05,

                    size=len(
                        simulated_X
                    )

                )

                simulated_X[
                    predictor
                ] = (
                    simulated_X[
                        predictor
                    ]
                    +
                    noise
                )

        simulations.append(
            simulated_X
        )

    return simulations



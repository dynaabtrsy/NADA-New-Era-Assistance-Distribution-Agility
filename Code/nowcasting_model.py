def clustered_bootstrap_predictions(
    data,
    outcome,
    predictors,
    model_name,
    future_data,
    n_bootstrap=5000,
    random_seed=42
):

    rng = np.random.default_rng(
        random_seed
    )

    available_districts = (
        data[DISTRICT_COL]
        .dropna()
        .unique()
        .tolist()
    )

    n_districts = len(
        available_districts
    )

    predictions = []

    for b in range(
        n_bootstrap
    ):

        sampled_districts = rng.choice(

            available_districts,

            size=n_districts,

            replace=True

        )

        bootstrap_parts = []

        for district in sampled_districts:

            district_data = data[
                data[DISTRICT_COL]
                ==
                district
            ]

            bootstrap_parts.append(
                district_data
            )

        bootstrap_data = pd.concat(
            bootstrap_parts,
            ignore_index=True
        )

        bootstrap_data = bootstrap_data.dropna(
            subset=[
                outcome
            ] + predictors
        )

        if len(bootstrap_data) < 5:
            continue

        model = create_models()[
            model_name
        ]

        try:

            model.fit(

                bootstrap_data[
                    predictors
                ],

                bootstrap_data[
                    outcome
                ]

            )

            pred = model.predict(
                future_data[
                    predictors
                ]
            )

            predictions.append(
                pred
            )

        except Exception:
            continue

    if len(predictions) == 0:

        raise ValueError(
            "No valid bootstrap predictions."
        )

    return np.vstack(
        predictions
    )



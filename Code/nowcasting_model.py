# 37. COMBINE BOOTSTRAP + MONTE CARLO
# ============================================================

def combine_uncertainty(

    bootstrap_predictions,
    mc_predictions,
    n_draws=5000,
    random_seed=42

):

    rng = np.random.default_rng(
        random_seed
    )

    n_boot = len(
        bootstrap_predictions
    )

    n_mc = len(
        mc_predictions
    )

    boot_idx = rng.integers(

        0,
        n_boot,
        size=n_draws

    )

    mc_idx = rng.integers(

        0,
        n_mc,
        size=n_draws

    )

    combined = (

        bootstrap_predictions[
            boot_idx
        ]

        +

        (
            mc_predictions[
                mc_idx
            ]

            -

            mc_predictions.mean(
                axis=0
            )
        )

    )

    return combined



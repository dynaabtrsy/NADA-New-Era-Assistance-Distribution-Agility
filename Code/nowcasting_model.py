def pchip_complete_district(
    district_df,
    outcome_column
):

    observed = (
        district_df[
            district_df[YEAR_COL]
            .isin(HIES_YEARS)
        ]
        [
            [
                YEAR_COL,
                outcome_column
            ]
        ]
        .dropna()
        .sort_values(YEAR_COL)
    )

    if len(observed) < 3:

        return pd.Series(
            np.nan,
            index=ALL_YEARS,
            dtype=float
        )

    x = (
        observed[YEAR_COL]
        .astype(float)
        .values
    )

    y = (
        observed[outcome_column]
        .astype(float)
        .values
    )

    pchip = PchipInterpolator(
        x,
        y
    )

    result = {}

    for year in ALL_YEARS:

        if year in HIES_YEARS:

            idx = list(x).index(
                float(year)
            )

            result[year] = y[idx]

        elif year in INTERPOLATION_YEARS:

            result[year] = float(
                pchip(year)
            )

        else:

            result[year] = np.nan

    return pd.Series(result)



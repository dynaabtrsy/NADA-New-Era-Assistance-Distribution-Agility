# 19. METRICS
# ============================================================

def calculate_metrics(
    y_true,
    y_pred
):

    mae = mean_absolute_error(
        y_true,
        y_pred
    )

    rmse = np.sqrt(
        mean_squared_error(
            y_true,
            y_pred
        )
    )

    # MAPE
    nonzero = (
        np.asarray(y_true) != 0
    )

    if nonzero.sum() > 0:

        mape = np.mean(
            np.abs(
                (
                    np.asarray(y_true)[nonzero]
                    -
                    np.asarray(y_pred)[nonzero]
                )
                /
                np.asarray(y_true)[nonzero]
            )
        ) * 100

    else:

        mape = np.nan

    # R²
    if len(y_true) >= 2:

        r2 = r2_score(
            y_true,
            y_pred
        )

    else:

        r2 = np.nan

    return (
        mae,
        rmse,
        mape,
        r2
    )


# ============================================================
# 20. POOLED LOOCV
# ============================================================
#
# IMPORTANT:
#
# Since we now have 6 years:
#
# 11 districts × 2 observations per district
# is no longer the previous setup.
#
# We use leave-one-observation-out:
#
# Each individual district-year observation is removed.
#
# Total expected observations:
#
# 11 districts × 6 years = 66
#
# assuming complete data.
#
# ============================================================

def pooled_loocv(
    data,
    outcome,
    predictors,
    model_name
):

    clean = data.dropna(
        subset=[
            outcome
        ] + predictors
    ).copy()

    clean = clean.reset_index(
        drop=True
    )

    predictions = []

    actuals = []

    prediction_records = []

    for i in range(
        len(clean)
    ):

        train = clean.drop(
            index=i
        )

        test = clean.iloc[
            [i]
        ]

        if len(train) < 5:
            continue

        model = create_models()[
            model_name
        ]

        model.fit(

            train[
                predictors
            ],

            train[
                outcome
            ]

        )

        pred = model.predict(

            test[
                predictors
            ]

        )[0]

        actual = test[
            outcome
        ].iloc[0]

        predictions.append(
            pred
        )

        actuals.append(
            actual
        )

        prediction_records.append({

            DISTRICT_COL:
                test[
                    DISTRICT_COL
                ].iloc[0],

            YEAR_COL:
                test[
                    YEAR_COL
                ].iloc[0],

            "data_type":
                test[
                    "data_type"
                ].iloc[0],

            "actual":
                actual,

            "predicted":
                pred,

            "error":
                actual - pred,

            "absolute_error":
                abs(
                    actual - pred
                )

        })

    y_true = np.array(
        actuals
    )

    y_pred = np.array(
        predictions
    )

    mae, rmse, mape, r2 = (
        calculate_metrics(
            y_true,
            y_pred
        )
    )

    prediction_df = pd.DataFrame(
        prediction_records
    )

    return {

        "model":
            model_name,

        "observations":
            len(y_true),

        "MAE":
            mae,

        "RMSE":
            rmse,

        "MAPE":
            mape,

        "R2":
            r2,

        "predictions":
            prediction_df

    }


